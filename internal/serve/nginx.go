package serve

import (
	"fmt"
	"io"
	"path/filepath"
	"sort"
	"strings"
)

// NginxOptions controls the generated server block.
type NginxOptions struct {
	Output     string // crossdock output root
	Listen     string // e.g. "80" or "[::]:443 ssl"
	ServerName string
	Index      bool // autoindex
}

// WriteNginx renders an nginx server block equivalent to the built-in
// server: same paths, cache headers and content types.
func WriteNginx(w io.Writer, o NginxOptions) error {
	if o.Listen == "" {
		o.Listen = "80"
	}
	if o.ServerName == "" {
		o.ServerName = "_"
	}
	cur := filepath.Join(o.Output, "current")
	var b strings.Builder
	p := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	p("# Generated by `crossdock nginx-config`; regenerate rather than editing.\n")
	p("server {\n")
	p("    listen %s;\n", o.Listen)
	p("    server_name %s;\n\n", o.ServerName)
	p("    # current is a symlink swapped atomically on publish. nginx resolves\n")
	p("    # it on every open, so keep open_file_cache off for this server.\n")
	p("    root %s;\n", cur)
	p("    open_file_cache off;\n")
	p("    disable_symlinks off;\n")
	if o.Index {
		p("    autoindex on;\n")
	} else {
		p("    autoindex off;\n")
	}
	p("    add_header X-Content-Type-Options nosniff always;\n\n")

	p("    types {\n")
	type kv struct{ ext, typ string }
	byType := map[string][]string{}
	for ext, typ := range Types {
		byType[typ] = append(byType[typ], ext)
	}
	var lines []kv
	for typ, exts := range byType {
		sort.Strings(exts)
		lines = append(lines, kv{strings.Join(exts, " "), typ})
	}
	sort.Slice(lines, func(i, j int) bool { return lines[i].typ < lines[j].typ })
	for _, l := range lines {
		p("        %-40s %s;\n", strings.ReplaceAll(l.typ, "; charset=utf-8", ""), l.ext)
	}
	p("    }\n")
	p("    default_type application/octet-stream;\n")
	p("    charset utf-8;\n")
	p("    charset_types text/plain application/xml application/json;\n\n")

	p("    location ~ /\\. { return 404; }\n")
	p("    location ^~ %s { return 404; }\n\n", ControlPrefix)

	// add_header inside a location replaces inherited ones, so repeat nosniff.
	for _, r := range Rules {
		if r.Name == "default" {
			continue
		}
		p("    # %s\n", r.Name)
		p("    location ~ \"%s\" {\n", r.Pattern)
		p("        add_header Cache-Control \"%s\" always;\n", r.CacheControl)
		p("        add_header X-Content-Type-Options nosniff always;\n")
		if r.DefaultType != "" {
			p("        default_type %s;\n", strings.ReplaceAll(r.DefaultType, "; charset=utf-8", ""))
		}
		p("    }\n\n")
	}
	p("    location / {\n")
	p("        add_header Cache-Control \"%s\" always;\n", cacheDefault)
	p("        add_header X-Content-Type-Options nosniff always;\n")
	p("    }\n")
	p("}\n")
	_, err := io.WriteString(w, b.String())
	return err
}
