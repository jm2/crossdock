const pkginfo = `# Generated by makepkg
pkgname = tributary-bin
pkgbase = tributary-bin
pkgver = 1.2.3-1
pkgdesc = Example package
url = https://example.invalid
builddate = 1760000000
packager = Test <t@example.invalid>
size = 4096
arch = x86_64
license = MIT
license = Apache-2.0
depend = gtk4
depend = glibc
optdepend = foo: for bar
`

// writePkg creates a gzip-compressed pacman package for tests.
func writePkg(t *testing.T, dir, name, info string) string {
	t.Helper()
	var b bytes.Buffer
	gz := gzip.NewWriter(&b)
	tw := tar.NewWriter(gz)
	add := func(h *tar.Header, data string) {
		h.Size = int64(len(data))
		if h.Mode == 0 {
			h.Mode = 0o644
		}
		if err := tw.WriteHeader(h); err != nil {
			t.Fatal(err)
		}
		io.WriteString(tw, data)
	}
	add(&tar.Header{Name: ".PKGINFO", Typeflag: tar.TypeReg}, info)
	add(&tar.Header{Name: ".MTREE", Typeflag: tar.TypeReg}, "x")
	add(&tar.Header{Name: "usr/", Typeflag: tar.TypeDir, Mode: 0o755}, "")
	add(&tar.Header{Name: "usr/bin/", Typeflag: tar.TypeDir, Mode: 0o755}, "")
	add(&tar.Header{Name: "usr/bin/tributary", Typeflag: tar.TypeReg, Mode: 0o755}, "#!/bin/sh\n")
	tw.Close()
	gz.Close()
	p := filepath.Join(dir, name)
	if err := os.WriteFile(p, b.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
	return p
}

func TestReadPackage(t *testing.T) {
	p := writePkg(t, t.TempDir(), "tributary-bin-1.2.3-1-x86_64.pkg.tar.gz", pkginfo)
	pkg, err := ReadPackage(p)
	if err != nil {
		t.Fatal(err)
	}
	if pkg.Name() != "tributary-bin" || pkg.Version() != "1.2.3-1" || pkg.Arch() != "x86_64" {
		t.Errorf("got %s %s %s", pkg.Name(), pkg.Version(), pkg.Arch())
	}
	if got := strings.Join(pkg.Info["license"], ","); got != "MIT,Apache-2.0" {
		t.Errorf("license = %q", got)
	}
	want := "usr/ usr/bin/ usr/bin/tributary"
	if got := strings.Join(pkg.Files, " "); got != want {
		t.Errorf("files = %q, want %q", got, want)
	}
}

func readTarGz(t *testing.T, path string) map[string]string {
	t.Helper()
	f, err := os.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	gz, err := gzip.NewReader(f)
	if err != nil {
		t.Fatal(err)
	}
	tr := tar.NewReader(gz)
	out := map[string]string{}
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return out
		}
		if err != nil {
			t.Fatal(err)
		}
		b, _ := io.ReadAll(tr)
		out[h.Name] = string(b)
	}
}

func TestPublish(t *testing.T) {
	src, out := t.TempDir(), t.TempDir()
	writePkg(t, src, "tributary-bin-1.2.3-1-x86_64.pkg.tar.gz", pkginfo)
	anyInfo := strings.NewReplacer("tributary-bin", "docs", "arch = x86_64", "arch = any").Replace(pkginfo)
	writePkg(t, src, "docs-1.2.3-1-any.pkg.tar.gz", anyInfo)

	now := time.Unix(1760000000, 0)
	rel, err := publish.Begin(out, now)
	if err != nil {
		t.Fatal(err)
	}
	env := &publish.Env{Release: rel, Now: now, Logf: t.Logf}
	repo := config.Repo{Name: "jm2", Format: config.FormatArch, Source: src,
		Architectures: []string{"x86_64", "aarch64"}}
	if err := Publish(repo, env); err != nil {
		t.Fatal(err)
	}
	if err := rel.Commit(); err != nil {
		t.Fatal(err)
	}

	x86 := filepath.Join(publish.CurrentDir(out), "arch", "jm2", "x86_64")
	db := readTarGz(t, filepath.Join(x86, "jm2.db"))
	d := db["tributary-bin-1.2.3-1/desc"]
	for _, want := range []string{
		"%FILENAME%\ntributary-bin-1.2.3-1-x86_64.pkg.tar.gz\n\n",
		"%LICENSE%\nMIT\nApache-2.0\n\n",
		"%DEPENDS%\ngtk4\nglibc\n\n",
		"%SHA256SUM%\n",
	} {
		if !strings.Contains(d, want) {
			t.Errorf("desc missing %q:\n%s", want, d)
		}
	}
	if _, ok := db["docs-1.2.3-1/desc"]; !ok {
		t.Error("x86_64 db lacks the arch=any package")
	}
	if _, ok := db["tributary-bin-1.2.3-1/files"]; ok {
		t.Error(".db should not contain files entries")
	}
	files := readTarGz(t, filepath.Join(x86, "jm2.files"))
	if got := files["tributary-bin-1.2.3-1/files"]; got != "%FILES%\nusr/\nusr/bin/\nusr/bin/tributary\n\n" {
		t.Errorf("files entry = %q", got)
	}
	arm := readTarGz(t, filepath.Join(publish.CurrentDir(out), "arch", "jm2", "aarch64", "jm2.db"))
	if _, ok := arm["tributary-bin-1.2.3-1/desc"]; ok {
		t.Error("aarch64 db contains an x86_64 package")
	}
	if _, ok := arm["docs-1.2.3-1/desc"]; !ok {
		t.Error("aarch64 db lacks the arch=any package")
	}
}

func TestPublishKeepsNewestVersion(t *testing.T) {
	// The newer file sorts first in one case and last in the other, and
	// pkgrel 10 must beat pkgrel 9 numerically.
	for _, names := range [][2]string{{"a.pkg.tar.gz", "b.pkg.tar.gz"}, {"b.pkg.tar.gz", "a.pkg.tar.gz"}} {
		src, out := t.TempDir(), t.TempDir()
		writePkg(t, src, names[0], strings.Replace(pkginfo, "1.2.3-1", "1.2.3-9", 1))
		writePkg(t, src, names[1], strings.Replace(pkginfo, "1.2.3-1", "1.2.3-10", 1))
		rel, _ := publish.Begin(out, time.Now())
		var logged []string
		env := &publish.Env{Release: rel, Now: time.Now(), Logf: func(f string, a ...any) {
			logged = append(logged, fmt.Sprintf(f, a...))
		}}
		if err := Publish(config.Repo{Name: "jm2", Source: src}, env); err != nil {
			t.Fatal(err)
		}
		if err := rel.Commit(); err != nil {
			t.Fatal(err)
		}
		db := readTarGz(t, filepath.Join(publish.CurrentDir(out), "arch", "jm2", "x86_64", "jm2.db"))
		if _, ok := db["tributary-bin-1.2.3-10/desc"]; !ok {
			t.Errorf("%v: db lacks the newest version: %v", names, db)
		}
		if _, ok := db["tributary-bin-1.2.3-9/desc"]; ok {
			t.Errorf("%v: db holds the older version too", names)
		}
		var skips []string
		for _, l := range logged {
			if strings.Contains(l, "skipping") {
				skips = append(skips, l)
			}
		}
		older := filepath.Join(src, names[0])
		if len(skips) != 1 || !strings.Contains(skips[0], "skipping "+older+":") || !strings.Contains(skips[0], "1.2.3-9 is older than 1.2.3-10") {
			t.Errorf("%v: log = %q", names, logged)
		}
	}
}

func TestPublishRejectsSameVersionDifferentContents(t *testing.T) {
	src, out := t.TempDir(), t.TempDir()
	writePkg(t, src, "a.pkg.tar.gz", pkginfo)
	writePkg(t, src, "b.pkg.tar.gz", strings.Replace(pkginfo, "Example package", "Other package", 1))
	rel, _ := publish.Begin(out, time.Now())
	env := &publish.Env{Release: rel, Now: time.Now(), Logf: t.Logf}
	err := Publish(config.Repo{Name: "jm2", Source: src}, env)
	if err == nil || !strings.Contains(err.Error(), "different contents") {
		t.Fatalf("err = %v, want same-version error", err)
	}
}

func TestReadSigRefusesSymlink(t *testing.T) {
	dir := t.TempDir()
	if sig, err := readSig(filepath.Join(dir, "none.sig")); sig != nil || err != nil {
		t.Errorf("missing signature: %q, %v", sig, err)
	}
	secret := filepath.Join(dir, "signing.asc")
	os.WriteFile(secret, []byte("secret"), 0o600)
	link := filepath.Join(dir, "a.pkg.tar.zst.sig")
	if err := os.Symlink(secret, link); err != nil {
		t.Skip(err)
	}
	if sig, err := readSig(link); err == nil || sig != nil {
		t.Errorf("a symlinked signature must be refused: %q, %v", sig, err)
	}
}
